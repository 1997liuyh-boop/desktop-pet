use serde::{Deserialize, Serialize};

/// 食物类型 — 对标 VPet food.lps 的 type 字段
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum FoodType {
    /// 正餐
    Meal,
    /// 零食
    Snack,
    /// 饮料
    Drink,
    /// 功能性 (提神/应急)
    Functional,
    /// 药品
    Drug,
    /// 礼品 (主要加心情/好感)
    Gift,
}

/// 食物定义 — 1:1 复刻 VPet food.lps / moredrink.lps / drug.lps 的条目
/// 字段对应 VPet: Exp / Strength / StrengthDrink / StrengthFood / Health / Feeling / Likability
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Food {
    /// 名字 (同时是图片文件名: image/food/<name>.png)
    pub name: String,
    /// 食物类型
    pub food_type: FoodType,
    /// 经验
    pub exp: f64,
    /// 体力
    pub strength: f64,
    /// 口渴值 (StrengthDrink)
    pub strength_drink: f64,
    /// 饱腹值 (StrengthFood)
    pub strength_food: f64,
    /// 健康
    pub health: f64,
    /// 心情
    pub feeling: f64,
    /// 好感度
    pub likability: f64,
    /// 价格
    pub price: f64,
    /// 动画图名 (eat / drink / medicine)
    pub graph: String,
    /// 描述文案 (VPet 原版 desc)
    pub desc: String,
}

impl Food {
    /// 食物图片相对路径 (相对本项目 assets 根目录)
    pub fn image_rel_path(&self) -> String {
        format!("image/food/{}.png", self.name)
    }
}

/// 构造辅助 — 参数顺序与 lps 字段一致: Exp / Strength / StrengthDrink / StrengthFood / Health / Feeling / Likability / price
#[allow(clippy::too_many_arguments)]
fn food(
    name: &str,
    food_type: FoodType,
    graph: &str,
    exp: f64,
    strength: f64,
    strength_drink: f64,
    strength_food: f64,
    health: f64,
    feeling: f64,
    likability: f64,
    price: f64,
    desc: &str,
) -> Food {
    Food {
        name: name.into(),
        food_type,
        exp,
        strength,
        strength_drink,
        strength_food,
        health,
        feeling,
        likability,
        price,
        graph: graph.into(),
        desc: desc.into(),
    }
}

